export interface SanskritNumberItem {
  value: number;
  devanagariNumeral: string;
  word: string;
  iast: string;
  english: string;
  decadeGroup: string; // e.g. '1-10', '11-20', etc.
  decadeLabelDev: string; // 'प्रथमावलिः (१-१०)'
  breakdown?: string;
  alternatives?: string[];
  notes?: string;
}

export interface GenderNumberExample {
  number: number;
  devanagariNumeral: string;
  stem: string;
  masculine: {
    form: string;
    iast: string;
    example: string;
    exampleEn: string;
  };
  feminine: {
    form: string;
    iast: string;
    example: string;
    exampleEn: string;
  };
  neuter: {
    form: string;
    iast: string;
    example: string;
    exampleEn: string;
  };
  grammaticalRule: string;
}

export interface OrdinalNumberItem {
  rank: number;
  numeral: string;
  masculine: string;
  feminine: string;
  neuter: string;
  iast: string;
  english: string;
  example: string;
}

export interface VedicLargeNumberItem {
  exponent: number;
  powerOfTen: string;
  numericDisplay: string;
  sanskritName: string;
  iast: string;
  englishMeaning: string;
  source: string;
  description: string;
}

